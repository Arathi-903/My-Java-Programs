package Langugefundamentals_datatypes;

public class Autoboxing_Autounboxing {
	//Autoboxing;
	int b  = 100;
	Integer c = b;
			
	//Auto_Unboxing;
	Integer d = 100;
	int e = d;

	public static void main(String[] args) {
		Autoboxing_Autounboxing a1 = new Autoboxing_Autounboxing();
		
		System.out.println(a1.b);
		System.out.println(a1.c);
		System.out.println(a1.d);
		System.out.println(a1.e);
		
		
		

	}

}
